/** Pick the closest supported language for a browser locale. */
export function resolveLang(candidate) {
  const raw = String(candidate || "").trim();
  if (LANGS.includes(raw)) return raw;
  const lower = raw.toLowerCase();
  if (lower.startsWith("zh")) {
    if (/(cn|hans|sg)/.test(lower)) return "zh-CN";
    return "zh-TW";
  }
  return "en";
}

/** Look up a key and interpolate {placeholders}. */
export function t(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  let value = table[key];
  if (value === undefined) value = STRINGS.en[key];
  if (value === undefined) return key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}
